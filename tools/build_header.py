def process(path, check):
    rel = os.path.relpath(path, ROOT)
    relu = rel.replace('\\', '/')
    s = open(path, encoding='utf-8').read()
    if relu in SKIP or 'http-equiv="refresh"' in s:
        return None
    here, section = None, None
    for prefix, key, label, href in SECTIONS:
        if relu.startswith(prefix):
            here, section = key, ((label, href) if label else None); break
    if START in s:
        old = s[s.index(START):s.index(END) + len(END)]
        bar = old.split('class="kp-sub"')[1].split('</nav>')[0] if 'class="kp-sub"' in old else ''
        extra = re.findall(r'<a href="([^"]+)">([^<]+)</a>', bar)
        extra = [(t, h) for h, t in extra]
    else:
        m = re.search(r'<nav\b[^>]*>.*?</nav>', s, re.S)
        if not m: return None
        old = m.group(0)
        extra = []
        for h, t in re.findall(r'<a (?![^>]*class="(?:nav-back|nav-sub|nav-search|brand|wm)")[^>]*href="([^"]+)"[^>]*>([^<]+)</a>', old):
            t = t.strip()
            if h in GENERIC or (section and h == section[1]): continue
            if '#' in h or 'tiktok.com/@lipstick' in h or 'tiktok.com/@szndbykatoya' in h:
                extra.append((t, h))
    new = header(relu, here, section, extra)
    if re.match(r'<nav\b[^>]*class="back"', old):  # legal pages: back link sat inside the content column
        skip = '<a class="skip-link" href="#main">Skip to content</a>'
        s2 = s.replace(old, '', 1).replace(skip, skip + chr(10) + new, 1)
    else:
        s2 = s.replace(old, new, 1)
    for tag, ref in (('<link rel="stylesheet" href="/assets/kp-header.css" />', '</head>'),
                     ('<script src="/assets/kp-header.js" defer></script>', '</head>')):
        if tag not in s2: s2 = s2.replace(ref, f'{tag}\n{ref}', 1)
    if s2 != s:
        if not check: open(path, 'w', encoding='utf-8', newline='').write(s2)
        return rel, [t for t, _ in extra]
    return None


