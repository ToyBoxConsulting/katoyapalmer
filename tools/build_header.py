def bamboo_o(size=24, gid='kpog'):
    """Static copy of the gold bamboo-O the pages used to draw with JS (same geometry, rounded)."""
    cx = cy = 50; rm, half, bulge, seg, phase = 40, 2.9, 0.82, 7, -math.pi / 2
    out, inn = [], []
    for i in range(121):
        a = i / 120 * math.pi * 2; t = half + bulge * math.cos(seg * (a - phase))
        out.append(f'{cx + (rm + t) * math.cos(a):.1f} {cy + (rm + t) * math.sin(a):.1f}')
        inn.append(f'{cx + (rm - t) * math.cos(a):.1f} {cy + (rm - t) * math.sin(a):.1f}')
    d = 'M' + 'L'.join(out) + 'M' + 'L'.join(reversed(inn)) + 'Z'
    kn = ''
    for i in range(seg):
        a = phase + math.pi + i / seg * math.pi * 2; t = half + bulge * math.cos(seg * (a - phase)) + .6
        kn += (f'<line x1="{cx + (rm - t) * math.cos(a):.1f}" y1="{cy + (rm - t) * math.sin(a):.1f}" '
               f'x2="{cx + (rm + t) * math.cos(a):.1f}" y2="{cy + (rm + t) * math.sin(a):.1f}" stroke="#9C7A2E" stroke-width="1.5" opacity=".95"/>')
    return (f'<svg width="{size}" height="{size}" viewBox="0 0 100 100" style="display:block;overflow:visible" aria-hidden="true" focusable="false">'
            f'<defs><linearGradient id="{gid}" x1=".15" y1="0" x2=".7" y2="1"><stop offset="0" stop-color="#D2B064"/>'
            '<stop offset=".45" stop-color="#B8923F"/><stop offset="1" stop-color="#8A6A22"/></linearGradient></defs>'
            f'<path d="{d}" fill="url(#{gid})" fill-rule="evenodd"/>{kn}</svg>')


